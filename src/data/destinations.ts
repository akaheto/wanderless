export const DESTINATIONS_BY_ID = new Map(DESTINATIONS.map((d) => [d.id, d]));

export function getDestination(id: string): Destination | undefined {
  return DESTINATIONS_BY_ID.get(id);
}

export function destinationsByRegion(): { region: string; items: Destination[] }[] {
  const groups = new Map<string, Destination[]>();
  for (const d of DESTINATIONS) {
    const list = groups.get(d.region) ?? [];
    list.push(d);
    groups.set(d.region, list);
  }
  return [...groups.entries()]
    .map(([region, items]) => ({ region, items: items.sort((a, b) => a.name.localeCompare(b.name)) }))
    .sort((a, b) => a.region.localeCompare(b.region));
}
