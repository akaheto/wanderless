function seasons(code: string): Season[] {
  if (code.length !== 12) {
    throw new Error(`Season code must be 12 characters, got "${code}"`);
  }
  return [...code].map((c) => {
    if (c === "P") return "peak";
    if (c === "S") return "shoulder";
    if (c === "L") return "low";
    throw new Error(`Unknown season character "${c}" in "${code}"`);
  });
}

